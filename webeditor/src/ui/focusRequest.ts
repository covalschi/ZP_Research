// Запит фокуса між вкладками (W4 Task 5) — крихітний спільний контракт для переходів
// «клік у «Балансі» -> інша вкладка з відкритим саме тим записом».
//
// Чому з лічильником `nonce`, а не просто рядком: повторний клік по ТОМУ САМОМУ рядку після
// того, як адмін вручну перемкнув вибір усередині цільової вкладки, мусить СПРАЦЮВАТИ ще раз.
// Якби пропсом їхало лише значення, воно б не змінилось — React не побачив би нової залежності
// й ефект не спрацював. Nonce робить кожен клік окремою подією, лишаючи вкладку-приймач
// повним господарем свого стану між подіями (жодного «керованого ззовні вибору»).
//
// Модуль ui/, але чистий (без React) — той самий статус, що optionCollectors.ts.

export interface FocusRequest {
  value: string
  nonce: number
}

// Дерево адресується парою: гілка = ФАЙЛ (дубль Branch.Id дав би два файли з одним Id), вузол
// — Id усередині неї. Порожній nodeId = «просто відкрий цю гілку» (перехід із рядка гілки).
export interface TreeFocusRequest {
  filePath: string
  nodeId: string
  nonce: number
}
